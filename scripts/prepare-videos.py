#!/usr/bin/env python3
"""Build web previews without changing the original research videos (requires ffmpeg)."""
import concurrent.futures
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / 'media'
OUT = MEDIA / 'preview'
OUT.mkdir(exist_ok=True)


def encode(job):
    source, name, width, fps, rate, crf, audio = job
    target = OUT / (name + '.mp4')
    if not target.exists():
        temporary = target.with_suffix('.tmp.mp4')
        command = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
                   '-i', str(MEDIA / source), '-map', '0:v:0',
                   '-vf', f'scale={width}:-2:flags=lanczos,fps={fps}',
                   '-c:v', 'libx264', '-preset', 'slow', '-threads', '2',
                   '-crf', str(crf), '-maxrate', f'{rate}k', '-bufsize', f'{rate * 2}k',
                   '-g', str(fps * 2), '-keyint_min', str(fps), '-pix_fmt', 'yuv420p']
        command += ['-map', '0:a:0?', '-c:a', 'aac', '-b:a', '96k'] if audio else ['-an']
        subprocess.run(command + ['-movflags', '+faststart', str(temporary)], check=True)
        temporary.replace(target)
    return str(target.relative_to(ROOT)), target.stat().st_size


# Remux the original HD stream; native range requests can start before a 10 s chunk is complete.
hd = MEDIA / 'film-hd.mp4'
if not hd.exists():
    with tempfile.TemporaryDirectory(prefix='xp-film-remux-') as directory:
        joined = Path(directory) / 'joined.mp4'
        with joined.open('wb') as output:
            for part in [MEDIA / 'film_hd/init.mp4', *sorted((MEDIA / 'film_hd').glob('seg*.mp4'))]:
                with part.open('rb') as source:
                    shutil.copyfileobj(source, output)
        subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
                        '-i', str(joined), '-map', '0', '-c', 'copy', '-movflags', '+faststart', str(hd)], check=True)

jobs = [
    ('teaser.mp4', 'teaser', 1280, 30, 1400, 25, True),
    ('teaser.mp4', 'teaser-480', 854, 24, 650, 26, True),
    ('film.mp4', 'film-480', 854, 24, 650, 25, True),
    ('hero_backdrop.mp4', 'hero', 1440, 20, 800, 28, False),
    ('hero_backdrop_m.mp4', 'hero-mobile', 600, 20, 450, 28, False),
]
variants = {
    'media/teaser.mp4': {'preview': 'media/preview/teaser.mp4', 'low': 'media/preview/teaser-480.mp4'},
    'media/film-hd.mp4': {'preview': 'media/film.mp4', 'low': 'media/preview/film-480.mp4'},
    'media/hero_backdrop.mp4': {'preview': 'media/preview/hero.mp4'},
    'media/hero_backdrop_m.mp4': {'preview': 'media/preview/hero-mobile.mp4'},
}
for name in ['data_human', 'data_robot', 'anno_human', 'anno_robot', 'teleop_wall', 'teleop_modality']:
    jobs.append((name + '.mp4', name, 960, 24, 750, 26, False))
    jobs.append((name + '.mp4', name + '-small', 640, 20, 350, 27, False))
    variants[f'media/{name}.mp4'] = {'preview': f'media/preview/{name}.mp4', 'low': f'media/preview/{name}-small.mp4'}
for i in range(8):
    jobs += [(f'long_{i}.mp4', f'long_{i}', 468, 15, 220, 26, False),
             (f'lib/ego{i}.mp4', f'ego{i}', 480, 15, 260, 26, False)]
    variants[f'media/long_{i}.mp4'] = {'preview': f'media/preview/long_{i}.mp4'}
    variants[f'media/lib/ego{i}.mp4'] = {'preview': f'media/preview/ego{i}.mp4'}
for i in [0, 1, 2, 3, 5, 6]:
    jobs.append((f'live_{i}.mp4', f'live_{i}', 1280, 30, 900, 25, False))
    variants[f'media/live_{i}.mp4'] = {'preview': f'media/preview/live_{i}.mp4'}

with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
    for name, size in pool.map(encode, jobs):
        print(f'{name}: {size / 1e6:.2f} MB', flush=True)
# Bound preparation of the next region using known file sizes.
# Keep sizes for files up to the player's per-file warmup limit; never include HD fragments.
sizes = {str(p.relative_to(ROOT)): p.stat().st_size for p in sorted(MEDIA.rglob('*.mp4'))
         if p.stat().st_size <= 16 * 1024 * 1024 and 'film_hd' not in p.parts}
(ROOT / 'assets/video-variants.js').write_text(
    '// Generated by scripts/prepare-videos.py; originals remain available in HD.\n'
    'window.XP_VIDEO_VARIANTS = ' + json.dumps(variants, indent=2) + ';\n'
    'window.XP_VIDEO_SIZES = ' + json.dumps(sizes, separators=(',', ':')) + ';\n')
